export const NormalizedCropRectSchema = z
  .object({
    x: z.number().int().min(0).max(9999),
    y: z.number().int().min(0).max(9999),
    width: z.number().int().min(1).max(10000),
    height: z.number().int().min(1).max(10000),
  })
  .superRefine((rect, context) => {
    if (rect.x + rect.width > 10000 || rect.y + rect.height > 10000) {
      context.addIssue({
        code: 'custom',
        message: '裁切框不能超出来源页面边界。',
      })
    }
  })

export type LayoutSlot = {
  kind: 'slot'
  id: string
  sourcePageId: string | null
  cropRect: z.infer<typeof NormalizedCropRectSchema>
  fit: z.infer<typeof LayoutFitSchema>
  alignment: z.infer<typeof LayoutAlignmentSchema>
  rotation: z.infer<typeof RotationSchema>
  detailOf: string | null
  clarityRiskAcknowledged: boolean
}

export type LayoutSplit = {
  kind: 'split'
  id: string
  direction: z.infer<typeof LayoutSplitDirectionSchema>
  weights: number[]
  children: LayoutNode[]
}

export type LayoutNode = LayoutSlot | LayoutSplit

export const LayoutSlotSchema: z.ZodType<LayoutSlot> = z.object({
  kind: z.literal('slot'),
  id: z.uuid(),
  sourcePageId: z.string().min(1).nullable(),
  cropRect: NormalizedCropRectSchema,
  fit: LayoutFitSchema,
  alignment: LayoutAlignmentSchema,
  rotation: RotationSchema,
  detailOf: z.string().min(1).nullable(),
  clarityRiskAcknowledged: z.boolean(),
})

export const LayoutNodeSchema: z.ZodType<LayoutNode> = z.lazy(() =>
  z.union([
    LayoutSlotSchema,
    z
      .object({
        kind: z.literal('split'),
        id: z.uuid(),
        direction: LayoutSplitDirectionSchema,
        weights: z.array(z.number().int().min(1).max(9999)).min(2).max(24),
        children: z.array(LayoutNodeSchema).min(2).max(24),
      })
      .superRefine((split, context) => {
        if (split.weights.length !== split.children.length) {
          context.addIssue({
            code: 'custom',
            path: ['weights'],
            message: '分割比例数量必须与子区域数量一致。',
          })
        }
        if (split.weights.reduce((total, weight) => total + weight, 0) !== 10000) {
          context.addIssue({
            code: 'custom',
            path: ['weights'],
            message: '分割比例之和必须为 10000。',
          })
        }
      }),
  ]),
)

export const LayoutSectionSchema = z.object({
  id: z.uuid(),
  materialId: z.uuid(),
  heightWeight: z.number().int().min(1).max(10000),
  showContinuationTitle: z.boolean(),
  layout: LayoutNodeSchema,
})

export const LayoutSheetSchema = z
  .object({
    id: z.uuid(),
    order: z.number().int().nonnegative(),
    anchorSourcePageId: z.string().min(1),
    orientation: TargetOrientationSchema,
    margins: z.object({
      top: z.number().min(0).max(144),
      right: z.number().min(0).max(144),
      bottom: z.number().min(0).max(144),
      left: z.number().min(0).max(144),
    }),
    sectionGapPoints: z.number().min(0).max(72),
    slotGapPoints: z.number().min(0).max(36),
    locked: z.boolean(),
    autoGenerated: z.boolean(),
    templateId: LayoutTemplateIdSchema.nullable(),
    crossDirectoryConfirmed: z.boolean(),
    sections: z.array(LayoutSectionSchema).min(1).max(12),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
  })
  .superRefine((sheet, context) => {
    if (sheet.sections.reduce((total, section) => total + section.heightWeight, 0) !== 10000) {
      context.addIssue({
        code: 'custom',
        path: ['sections'],
        message: '拼版页成果区段高度比例之和必须为 10000。',
      })
    }
    const materialIds = new Set<string>()
    sheet.sections.forEach((section, index) => {
      if (materialIds.has(section.materialId)) {
        context.addIssue({
          code: 'custom',
          path: ['sections', index, 'materialId'],
          message: '同一成果在一张拼版页中只能有一个全宽区段。',
        })
      }
      materialIds.add(section.materialId)
    })
  })

export const CollageSettingsSchema = z
  .object({
    enabled: z.boolean(),
    defaultOrientation: TargetOrientationSchema,
    defaultMargins: z.object({
      top: z.number().min(0).max(144),
      right: z.number().min(0).max(144),
      bottom: z.number().min(0).max(144),
      left: z.number().min(0).max(144),
    }),
    defaultSectionGapPoints: z.number().min(0).max(72),
    defaultSlotGapPoints: z.number().min(0).max(36),
    autoCropEnabled: z.boolean(),
    autoCropSafetyMillimeters: z.number().min(0).max(20),
    rasterPreferredDpi: z.number().int().min(72).max(600),
    rasterMinimumAutoDpi: z.number().int().min(72).max(600),
    pdfWarningScale: z.number().min(0.1).max(1),
    pdfMinimumAutoScale: z.number().min(0.1).max(1),
    maxAutoSlotsPerSheet: z.number().int().min(1).max(12),
    maxManualSlotsPerSheet: z.number().int().min(1).max(24),
  })
  .superRefine((settings, context) => {
    if (settings.rasterPreferredDpi < settings.rasterMinimumAutoDpi) {
      context.addIssue({
        code: 'custom',
        path: ['rasterPreferredDpi'],
        message: '图片推荐 DPI 不能低于自动拼版最低 DPI。',
      })
    }
    if (settings.pdfWarningScale < settings.pdfMinimumAutoScale) {
      context.addIssue({
        code: 'custom',
        path: ['pdfWarningScale'],
        message: 'PDF 警告缩放比例不能低于自动拼版最低缩放比例。',
      })
    }
    if (settings.maxManualSlotsPerSheet < settings.maxAutoSlotsPerSheet) {
      context.addIssue({
        code: 'custom',
        path: ['maxManualSlotsPerSheet'],
        message: '手动拼版槽位上限不能低于自动拼版槽位上限。',
      })
    }
  })

