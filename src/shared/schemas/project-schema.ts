export const createDefaultProject = (
  input: {
    title: string
    ownerName?: string
    organization?: string
    purpose?: string
    compiledDate?: string
    outlineNodes?: OutlineNode[]
  },
  now = new Date(),
): Project => {
  const iso = now.toISOString()
  const date = input.compiledDate ?? iso.slice(0, 10)
  const ownerName = input.ownerName ?? ''
  const organization = input.organization ?? ''
  const purpose = input.purpose ?? ''

  return ProjectSchema.parse({
    id: crypto.randomUUID(),
    schemaVersion: 3,
    title: input.title,
    ownerName,
    organization,
    purpose,
    compiledDate: date,
    createdAt: iso,
    updatedAt: iso,
    projectDirectory: '.',
    assetStorageMode: 'copy',
    coverSettings: {
      enabled: true,
      title: input.title,
      ownerName,
      organization,
      purpose,
      compiledDate: date,
      insertBlankBackPage: true,
      showPageNumber: false,
      countInLogicalNumber: false,
    },
    tocSettings: {
      enabled: true,
      title: '支撑材料目录',
      showPageNumber: false,
      countInLogicalNumber: false,
    },
    pageNumberSettings: {
      enabled: true,
      bodyStartNumber: 1,
      position: 'bottomCenter',
      format: 'dash',
      fontSize: 12,
      bottomOffsetPoints: DEFAULT_PAGE_NUMBER_BOTTOM_OFFSET_POINTS,
      showOnDivider: true,
      showOnMaterialTitle: true,
    },
    exportSettings: {
      outputFileName: `${input.title}.pdf`,
      includeCover: true,
      includeToc: true,
      includeDividerPages: true,
      includeMaterialTitlePages: true,
      contentHeadingMode: 'firstPage',
      addPageNumbers: true,
      targetOrientation: 'portrait',
      margins: DEFAULT_PAGE_MARGINS_POINTS,
      imageQuality: 'standard',
      metadata: {
        title: input.title,
        author: ownerName,
        subject: purpose,
        creator: '个人支撑材料编排器',
        producer: 'SupportPackBuilder',
      },
      overwriteExisting: false,
      openAfterExport: false,
      revealAfterExport: true,
    },
    collageSettings: createDefaultCollageSettings(),
    layoutSheets: [],
    outlineNodes: input.outlineNodes ?? [],
  })
}
