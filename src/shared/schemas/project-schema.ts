export const MaterialSchema = z
  .object({
    id: z.uuid(),
    outlineNodeId: z.uuid(),
    title: z.string().min(1).max(300),
    category: z.string().max(100),
    sourceType: SourceTypeSchema,
    sourcePath: z.string().min(1),
    storedPath: z.string().min(1).nullable(),
    originalFileName: z.string().min(1).max(255),
    fileHash: z.string().regex(/^[a-f0-9]{64}$/i),
    fileSize: z.number().int().nonnegative(),
    modifiedTime: z.number().int().nonnegative(),
    pageCount: z.number().int().positive(),
    selectedPageRanges: z.string().min(1).max(4096),
    pageOrder: z.array(z.string().min(1)),
    rotationByPage: z.record(z.string(), RotationSchema),
    removedPages: z.array(z.string().min(1)),
    enabled: z.boolean(),
    startPolicy: MaterialStartPolicySchema,
    insertTitlePage: z.boolean(),
    notes: z.string().max(5000),
    validationStatus: ValidationStatusSchema,
    validationMessages: z.array(ValidationMessageSchema),
    order: z.number().int().nonnegative(),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
    sourceItems: z.array(MaterialSourceSchema).min(1),
  })
  .superRefine((material, context) => {
    if (material.sourceType === 'imageCollection' && material.sourceItems.length < 2) {
      context.addIssue({
        code: 'custom',
        path: ['sourceItems'],
        message: '图片集合至少需要两张图片。',
      })
    }
    if (
      material.sourceType === 'imageCollection' &&
      material.sourceItems.some((source) => source.sourceType !== 'image')
    ) {
      context.addIssue({
        code: 'custom',
        path: ['sourceItems'],
        message: '图片集合只能包含图片来源。',
      })
    }
    if (
      ['pdf', 'image', 'office'].includes(material.sourceType) &&
      material.sourceItems.length !== 1
    ) {
      context.addIssue({
        code: 'custom',
        path: ['sourceItems'],
        message: '单文件材料必须且只能包含一个来源文件；多文件成果请使用混合材料。',
      })
    }
    if (material.sourceType === 'mixed' && material.sourceItems.length < 2) {
      context.addIssue({
        code: 'custom',
        path: ['sourceItems'],
        message: '混合材料至少需要两个来源文件。',
      })
    }
    if (
      material.sourceItems.length === 1 &&
      ['pdf', 'image', 'office'].includes(material.sourceType) &&
      material.sourceItems[0]?.sourceType !== material.sourceType
    ) {
      context.addIssue({
        code: 'custom',
        path: ['sourceItems', 0, 'sourceType'],
        message: '单文件材料类型必须与来源文件类型一致。',
      })
    }
    material.sourceItems.forEach((source, index) => {
      if (source.sourceType === 'office' && !source.conversion) {
        context.addIssue({
          code: 'custom',
          path: ['sourceItems', index, 'conversion'],
          message: 'Office 来源必须包含可用的 PDF 转换快照。',
        })
      }
      if (source.sourceType !== 'office' && source.conversion !== undefined) {
        context.addIssue({
          code: 'custom',
          path: ['sourceItems', index, 'conversion'],
          message: '非 Office 来源不能包含 Office 转换快照。',
        })
      }
      if (source.sourceType === 'image' && source.pageCount !== 1) {
        context.addIssue({
          code: 'custom',
          path: ['sourceItems', index, 'pageCount'],
          message: '图片来源页数必须为 1。',
        })
      }
    })
  })

